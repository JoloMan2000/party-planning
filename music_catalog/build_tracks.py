def slug(s):
    s = s.lower()
    s = s.replace("&", " and ")
    s = re.sub(r"[’'`´]", "", s)
    s = re.sub(r"[^a-z0-9]+", "_", s)
    s = re.sub(r"_+", "_", s).strip("_")
    return s


def make_id(artist, title, used):
    base = slug(artist) + "_" + slug(title)
    cand = base
    i = 2
    while cand in used:
        cand = f"{base}_{i}"
        i += 1
    used.add(cand)
    return cand


